import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const git = (...args) => {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
};

const fullBuildId = process.env.GITHUB_SHA || process.env.SOURCE_VERSION || git('rev-parse', 'HEAD') || 'development';
const buildId = fullBuildId === 'development' ? fullBuildId : fullBuildId.slice(0, 12);
const releasedAt = process.env.SMOKESTACK_RELEASED_AT || git('show', '-s', '--format=%cI', 'HEAD') || new Date(0).toISOString();
const release = {
  app: 'Smoke Stack',
  version: packageJson.version,
  buildNumber: Number(packageJson.smokestack?.buildNumber || 0),
  buildId,
  channel: packageJson.smokestack?.channel || 'alpha',
  releasedAt,
  webUrl: packageJson.smokestack?.webUrl || '/',
  minimumSupportedVersion: packageJson.smokestack?.minimumSupportedVersion || packageJson.version,
};

fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/version.json'), `${JSON.stringify(release, null, 2)}\n`);
fs.writeFileSync(
  path.join(root, 'src/generated/release.ts'),
  `// Generated by scripts/generate-release-metadata.mjs. Do not edit manually.\nexport const CURRENT_RELEASE = ${JSON.stringify(release, null, 2)} as const;\n`,
);

console.log(`[release] ${release.version} build ${release.buildNumber} (${release.buildId})`);
